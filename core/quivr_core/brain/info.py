def _check_approved_model(model_name: str) -> str:
    """Validate that a model name is in the approved registry.

    Raises ValueError if the model is not approved.
    Returns the model_name if approved.
    """
    import logging as _lg
    _log = _lg.getLogger("lineaje.model_registry")
    if model_name.lower().strip() in _UNAPPROVED_LLM_ALIASES:
        _log.error(
            "POLICY VIOLATION AI_APP_SEC_006: Model '%s' is not in the approved registry. "
            "Use only models from the organization's approved list: %s",
            model_name, _APPROVED_LLM_REGISTRY,
        )
        raise ValueError(
            "Model '%s' is not in the organization's approved LLM registry. "
            "Approved models: %s" % (model_name, _APPROVED_LLM_REGISTRY)
        )
    if _APPROVED_LLM_REGISTRY and model_name not in _APPROVED_LLM_REGISTRY:
        _log.warning(
            "Model '%s' is not explicitly listed in the approved registry.",
            model_name,
        )
    return model_name
